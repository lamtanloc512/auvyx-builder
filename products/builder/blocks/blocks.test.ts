/**
 * Block contracts, run with the real @wordpress/blocks parser/validator:
 * - PHP-generated markup (patterns, Markup.php) matches each block's JS save();
 * - saved HTML never depends on auvyx styles (classes are added at render, ADR 0002).
 */
import { describe, expect, test } from "bun:test";
import { createBlock, getSaveContent, parse, type Block } from "@wordpress/blocks";
import "../editor/index";

const walk = (blocks: Block[]): Block[] =>
  blocks.flatMap((block) => [block, ...walk(block.innerBlocks)]);

const expectValid = async (fixture: string, minBlocks: number) => {
  const html = await Bun.file(`${import.meta.dir}/../${fixture.includes("/") ? fixture : `tests/fixtures/${fixture}`}`).text();
  const blocks = walk(parse(html));
  expect(blocks.length).toBeGreaterThanOrEqual(minBlocks);
  for (const block of blocks) {
    expect({ name: block.name, valid: block.isValid }).toEqual({ name: block.name, valid: true });
  }
  return blocks;
};

describe("generated markup is valid for the blocks' JS save()", () => {
  test("PHP: landing pattern (Markup.php)", async () => {
    await expectValid("landing.html", 20);
  });

  test("Auvyx Studio (Scala BlockMarkup): supports, rich text, raw blocks", async () => {
    // The core/paragraph raw block is not registered in this test environment, so 5 Auvyx blocks are checked.
    const blocks = await expectValid("studio.html", 5);
    const section = blocks[0];
    expect(section?.attributes).toMatchObject({ tagName: "div", align: "full", anchor: "hero", className: "custom" });
    expect(String(blocks[1]?.attributes.content)).toBe("Hello <strong>world</strong> &amp; co");
    expect(blocks[3]?.attributes.url).toBe('https://example.com/?a=1&b="2"');
  });
});

// Auvyx Builder's library and Auvyx Builder Pro's (docs/editions.md), both generated by apps/studio TemplatesSuite.
for (const [name, rel] of [["Auvyx Builder", "patterns/generated"]] as const) {
  describe(`template library of ${name} (generated by apps/studio TemplatesSuite)`, () => {
    const dir = `${import.meta.dir}/../${rel}`;
    const manifest: { id: string }[] = JSON.parse(require("node:fs").readFileSync(`${dir}/manifest.json`, "utf8"));
    test.each(manifest.map((t) => t.id))("%s is valid block markup", async (id) => {
      // Header elements are a single platform block (site logo, cart…): no Auvyx block to count.
      await expectValid(`${rel}/${id}.html`, id.startsWith("wp-part-el-") ? 0 : 1);
    });
  });
}

describe("Flatsome import (FlatsomeImportSuite snapshot)", () => {
  // a third-party page: kept in the private repository only (tools/export-public.ts leaves it out)
  const here = require("node:fs").existsSync(`${import.meta.dir}/../tests/fixtures/flatsome/mega-shop.html`);
  test.skipIf(!here)("the converted Mega Shop page is valid Auvyx block markup", async () => {
    await expectValid("tests/fixtures/flatsome/mega-shop.html", 60);
  });
});

describe("compatibility: markup saved by released versions stays valid (ADR 0003)", () => {
  const dir = `${import.meta.dir}/../tests/fixtures/compat`;
  const files: string[] = require("node:fs").readdirSync(dir).filter((f: string) => f.endsWith(".html"));
  test.each(files)("%s", async (file) => {
    await expectValid(`tests/fixtures/compat/${file}`, 1);
  });
});

describe("saved HTML ignores auvyx styles", () => {
  const auvyx = { v: 1, styles: { base: { default: { color: "red" } } } };
  test.each([
    ["auvyx/section", {}],
    ["auvyx/heading", { content: "Hi", level: 3 }],
    ["auvyx/text", { content: "Hi" }],
    ["auvyx/button", { text: "Go", url: "https://example.com" }],
  ])("%s", (name, attributes) => {
    const plain = createBlock(name, attributes);
    const styled = createBlock(name, { ...attributes, auvyx });
    expect(getSaveContent(styled.name, styled.attributes, [])).toBe(
      getSaveContent(plain.name, plain.attributes, [])
    );
  });
});
