/**
 * One-off: shared/icons.json — the icon set of the Auvyx Icon block (Lucide, ISC license), used by the Studio
 * (Scala, generated), the block editor (TS import) and PHP rendering (generated/icons.php).
 *   bun tools/gen-icons.ts <path to lucide-react/dist/esm/icons>
 */
import { join } from "node:path";

const dirs = process.argv.slice(2);
if (dirs.length === 0) throw new Error("usage: bun tools/gen-icons.ts <lucide icons dir> [older lucide dir for brand icons]");
const read = async (file: string): Promise<string> => {
  for (const dir of dirs) {
    for (const ext of [".mjs", ".js"]) {
      const f = Bun.file(join(dir, `${file}${ext}`));
      if (await f.exists()) return f.text();
    }
  }
  throw new Error(`icon not found: ${file}`);
};
const names = [
  "check", "circle-check", "star", "heart", "zap", "shield-check", "lock", "globe", "phone", "mail", "map-pin",
  "clock", "calendar", "users", "user", "award", "rocket", "sparkles", "layers", "layout-grid", "palette",
  "code-xml", "smartphone", "monitor", "truck", "credit-card", "gift", "shopping-cart", "shopping-bag",
  "message-circle", "camera", "play", "leaf", "sun", "moon", "cloud", "settings", "search", "thumbs-up",
  "trending-up", "chart-bar", "target", "lightbulb", "headphones", "package", "wallet", "arrow-right",
  "quote", "facebook", "instagram", "twitter", "youtube", "linkedin",
];
const icons: Record<string, string> = {};
for (const name of names) {
  let file = name;
  let src = await read(file);
  while (!src.includes("const __iconData") && !src.includes("const __iconNode")) {
    file = src.match(/from '\.\/([\w-]+)\.m?js'/)?.[1] ?? "";
    if (!file) throw new Error(`cannot resolve ${name}`);
    src = await read(file);
  }
  // v1: `const __iconData = {..., node: [...]}`; v0: `const __iconNode = [...]`.
  const literal = src.match(/const __iconData = (\{[\s\S]*?\n\});/)?.[1]
    ?? `{ node: ${src.match(/const __iconNode = (\[[\s\S]*?\n\]);/)?.[1]} }`;
  const data = new Function(`return (${literal});`)() as { node: [string, Record<string, string>][] };
  icons[name] = data.node
    .map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => `${k.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase())}="${v}"`).join(" ")}/>`)
    .join("");
}
await Bun.write(join(import.meta.dir, "../shared/icons.json"), JSON.stringify({ $comment: "Lucide icons (ISC). Generated by tools/gen-icons.ts.", icons }, null, 1) + "\n");
console.log(`${Object.keys(icons).length} icons`);
